"""Window layout and styling, separated from task and storage coordination."""
from __future__ import annotations

import os
import sys
import tkinter as tk
from tkinter import ttk

from .models import OUTPUT_FORMATS
from .widgets import HoverText

BG, PAPER, INK = '#F3F5F8', '#FFFFFF', '#192A3C'
MUTED, ACCENT, ERROR, GREEN = '#66768A', '#2864D7', '#B13740', '#14755C'


class MainView:
    def _style(self) -> None:
        font = 'PingFang SC' if sys.platform == 'darwin' else ('Microsoft YaHei UI' if os.name == 'nt' else 'sans-serif')
        self.root.option_add('*Font', (font, 11))
        style = ttk.Style(self.root)
        style.theme_use('clam')
        style.configure('.', font=(font, 11), foreground=INK)
        style.configure('TFrame', background=BG)
        style.configure('Card.TFrame', background=PAPER)
        style.configure('TLabel', background=BG)
        style.configure('Card.TLabel', background=PAPER)
        style.configure('Muted.TLabel', background=PAPER, foreground=MUTED, font=(font, 10))
        style.configure('Small.TLabel', background=BG, foreground=MUTED, font=(font, 10))
        style.configure('Title.TLabel', font=(font, 21, 'bold'))
        style.configure('Section.TLabel', background=PAPER, font=(font, 12, 'bold'))
        style.configure('Song.TLabel', background=PAPER, font=(font, 15, 'bold'))
        style.configure('Error.TLabel', background=PAPER, foreground=ERROR, font=(font, 10))
        style.configure('Good.TLabel', background=PAPER, foreground=GREEN, font=(font, 10))
        style.configure('TButton', padding=(9, 4), background='#F7F9FC', borderwidth=1)
        style.map('TButton', background=[('active', '#E7EDFA')], foreground=[('disabled', '#9AA5B4')])
        style.configure('Accent.TButton', background=ACCENT, foreground='white', padding=(12, 5))
        style.map('Accent.TButton', background=[('disabled', '#C8D1DF'), ('active', '#2054B7')],
                  foreground=[('disabled', '#F5F7FA'), ('!disabled', 'white')])
        style.configure('TEntry', padding=(6, 5), fieldbackground='white')
        style.configure('TSpinbox', padding=(6, 5))
        style.configure('TCombobox', padding=(5, 5))
        style.configure('TCheckbutton', background=PAPER)
        style.configure('Toolbar.TCheckbutton', background=BG)
        style.configure('Treeview', rowheight=34, fieldbackground=PAPER, background=PAPER, borderwidth=0)
        style.configure('Treeview.Heading', background='#F1F4F9', font=(font, 10, 'bold'), padding=(7, 8))
        style.map('Treeview', background=[('selected', '#DFEAFD')], foreground=[('selected', INK)])
        style.configure('Horizontal.TProgressbar', background=ACCENT, troughcolor='#E5EBF3', borderwidth=0, thickness=8)

    def _build_ui(self) -> None:
        menu = tk.Menu(self.root)
        file_menu = tk.Menu(menu, tearoff=False)
        for label, command in [('添加音频…', self._pick_files), ('添加文件夹…', self._pick_folder),
                               ('打开项目…', self._open_project), ('保存项目…', self._save_project_dialog)]:
            file_menu.add_command(label=label, command=command)
        file_menu.add_separator()
        file_menu.add_command(label='导入旧版 Excel…', command=self._open_excel)
        file_menu.add_command(label='导出 Excel 配置…', command=self._save_excel)
        file_menu.add_separator()
        file_menu.add_command(label='清空工作区', command=self._clear_project)
        menu.add_cascade(label='文件', menu=file_menu)
        edit_menu = tk.Menu(menu, tearoff=False)
        edit_menu.add_command(label='撤销移除片段', command=self._undo_remove)
        edit_menu.add_command(label='将当前时间范围应用到全部片段…', command=self._apply_range_all)
        menu.add_cascade(label='编辑', menu=edit_menu)
        help_menu = tk.Menu(menu, tearoff=False)
        help_menu.add_command(label='音频引擎设置…', command=self._settings)
        help_menu.add_command(label='查看运行日志', command=self._show_logs)
        help_menu.add_command(label='打开日志文件夹', command=lambda: self._open_path(self.log_path.parent))
        help_menu.add_command(label='复制诊断信息', command=self._copy_diagnostics)
        menu.add_cascade(label='帮助', menu=help_menu)
        self.root.configure(menu=menu)

        outer = ttk.Frame(self.root, padding=(18, 12, 18, 10))
        outer.pack(fill='both', expand=True)
        outer.columnconfigure(0, weight=1)
        outer.rowconfigure(3, weight=1)
        header = ttk.Frame(outer)
        header.grid(row=0, column=0, sticky='ew', pady=(0, 9))
        ttk.Label(header, text='MusicCutter', style='Title.TLabel').pack(side='left')
        ttk.Label(header, text='本地音频剪辑  /  4.0', style='Small.TLabel').pack(side='left', padx=14, pady=(8, 0))
        ttk.Button(header, text='运行日志', command=self._show_logs).pack(side='right')
        ttk.Button(header, text='设置', command=self._settings).pack(side='right', padx=6)

        steps = ttk.Frame(outer)
        steps.grid(row=1, column=0, sticky='ew', pady=(0, 8))
        self.step_labels = []
        for text in ('01  导入音频', '02  选择与试听片段', '03  导出与查看结果'):
            label = tk.Label(steps, text=text, anchor='w', bg='#E8EDF5', fg=MUTED, padx=12, pady=5)
            label.pack(side='left', fill='x', expand=True, padx=(0, 3))
            self.step_labels.append(label)
        self._set_step(0)
        toolbar = ttk.Frame(outer)
        toolbar.grid(row=2, column=0, sticky='ew', pady=(0, 9))
        self.import_button = ttk.Button(toolbar, text='＋ 添加音频', command=self._pick_files, style='Accent.TButton')
        self.import_button.pack(side='left')
        self.folder_button = ttk.Button(toolbar, text='添加文件夹', command=self._pick_folder)
        self.folder_button.pack(side='left', padx=7)
        self.recursive_check = ttk.Checkbutton(toolbar, text='包含子文件夹', variable=self.recursive,
                                              style='Toolbar.TCheckbutton', command=self._setting_changed)
        self.recursive_check.pack(side='left', padx=3)
        self.cancel_import_button = ttk.Button(toolbar, text='取消导入', command=self._cancel_import)
        self.cancel_import_button.pack(side='left', padx=6)
        self.save_button = ttk.Button(toolbar, text='保存项目', command=self._save_project_dialog)
        self.save_button.pack(side='right')
        self.open_button = ttk.Button(toolbar, text='打开项目', command=self._open_project)
        self.open_button.pack(side='right', padx=7)

        area = ttk.Panedwindow(outer, orient='horizontal')
        area.grid(row=3, column=0, sticky='nsew')
        left = ttk.Frame(area, style='Card.TFrame', padding=14)
        right = ttk.Frame(area, style='Card.TFrame', padding=10)
        area.add(left, weight=5)
        area.add(right, weight=5)
        lefthead = ttk.Frame(left, style='Card.TFrame')
        lefthead.pack(fill='x', pady=(0, 9))
        ttk.Label(lefthead, text='音频与片段', style='Section.TLabel').pack(side='left')
        ttk.Label(lefthead, textvariable=self.count_var, style='Muted.TLabel').pack(side='right')
        holder = ttk.Frame(left, style='Card.TFrame')
        holder.pack(fill='both', expand=True)
        self.tree = ttk.Treeview(holder, columns=('range', 'state'), show='tree headings', selectmode='browse')
        self.tree.heading('#0', text='源音频 / 输出片段')
        self.tree.column('#0', width=260, minwidth=150, stretch=True)
        self.tree.heading('range', text='开始 · 时长')
        self.tree.column('range', width=135, minwidth=110, stretch=False)
        self.tree.heading('state', text='状态')
        self.tree.column('state', width=75, minwidth=65, stretch=False)
        scroll = ttk.Scrollbar(holder, command=self.tree.yview)
        self.tree.configure(yscrollcommand=scroll.set)
        scroll.pack(side='right', fill='y')
        self.tree.pack(side='left', fill='both', expand=True)
        self.tree.tag_configure('error', foreground=ERROR)
        self.tree.tag_configure('success', foreground=GREEN)
        self.tree.tag_configure('source', foreground=MUTED)
        self.tree.bind('<<TreeviewSelect>>', self._on_select)
        self.tree.bind('<Delete>', lambda _: self._delete())
        row = ttk.Frame(left, style='Card.TFrame')
        row.pack(fill='x', pady=(12, 0))
        self.add_clip_button = ttk.Button(row, text='＋ 新增片段', command=self._new_clip)
        self.add_clip_button.pack(side='left')
        self.clone_button = ttk.Button(row, text='复制', command=self._clone)
        self.clone_button.pack(side='left', padx=5)
        self.delete_button = ttk.Button(row, text='移除', command=self._delete)
        self.delete_button.pack(side='left')
        self.relink_button = ttk.Button(row, text='定位源文件', command=self._relink)
        self.relink_button.pack(side='right')

        self.song_label = ttk.Label(right, textvariable=self.song_var, style='Song.TLabel', width=1)
        self.song_label.pack(fill='x', pady=(5, 2))
        self.info_label = ttk.Label(right, textvariable=self.info_var, style='Muted.TLabel', width=1)
        self.info_label.pack(fill='x')
        HoverText(self.song_label, lambda: str(self._current().source) if self._current() else '')
        HoverText(self.info_label, self.info_var.get)
        wavehead = ttk.Frame(right, style='Card.TFrame')
        wavehead.pack(fill='x', pady=(9, 3))
        ttk.Label(wavehead, textvariable=self.wave_var, style='Muted.TLabel').pack(side='left')
        self.wave_button = ttk.Button(wavehead, text='加载波形', command=self._show_wave)
        self.wave_button.pack(side='right')
        self.canvas = tk.Canvas(right, height=64, bg='#F4F7FD', highlightthickness=0)
        self.canvas.pack(fill='x', pady=(0, 8))
        self.canvas.bind('<Configure>', lambda _: self._draw_wave())
        self.canvas.bind('<Button-1>', self._drag_begin)
        self.canvas.bind('<B1-Motion>', self._drag_move)
        self.canvas.bind('<ButtonRelease-1>', self._drag_end)
        fields = ttk.Frame(right, style='Card.TFrame')
        fields.pack(fill='x')
        fields.columnconfigure(0, weight=1)
        fields.columnconfigure(1, weight=1)
        ttk.Label(fields, text='开始位置', style='Card.TLabel').grid(row=0, column=0, sticky='w')
        ttk.Label(fields, text='片段时长（秒）', style='Card.TLabel').grid(row=0, column=1, sticky='w', padx=(14, 0))
        self.start_entry = ttk.Entry(fields, textvariable=self.start_var, width=16)
        self.start_entry.grid(row=1, column=0, sticky='ew', pady=(5, 0))
        self.length_entry = ttk.Spinbox(fields, from_=0.1, to=999999999, increment=0.1,
                                        textvariable=self.length_var, format='%.1f', width=16)
        self.length_entry.grid(row=1, column=1, sticky='ew', padx=(14, 0), pady=(5, 0))
        for entry in (self.start_entry, self.length_entry):
            entry.bind('<Return>', lambda _: self._apply())
            entry.bind('<FocusOut>', lambda _: self._apply(quiet=True))
        ttk.Label(right, textvariable=self.end_var, style='Muted.TLabel').pack(anchor='w', pady=(4, 6))
        names = ttk.Frame(right, style='Card.TFrame')
        names.pack(fill='x')
        names.columnconfigure(0, weight=1)
        ttk.Label(names, text='输出文件名', style='Card.TLabel').grid(row=0, column=0, sticky='w')
        self.name_entry = ttk.Entry(names, textvariable=self.name_var)
        self.name_entry.grid(row=1, column=0, sticky='ew', pady=(5, 0))
        self.format_combo = ttk.Combobox(names, textvariable=self.format_var,
                                        values=[fmt.upper() for fmt in OUTPUT_FORMATS], state='readonly', width=6)
        self.format_combo.grid(row=1, column=1, padx=(8, 0), pady=(5, 0))
        self.format_combo.bind('<<ComboboxSelected>>', self._format_changed)
        editor_box = ttk.Frame(right, style='Card.TFrame', height=28)
        editor_box.pack(fill='x', pady=(6, 7))
        editor_box.pack_propagate(False)
        self.editor_label = ttk.Label(editor_box, textvariable=self.editor_var, style='Muted.TLabel', wraplength=490, anchor='nw')
        self.editor_label.pack(fill='both', expand=True)
        self.editor_label.bind('<Configure>', lambda e: self.editor_label.configure(wraplength=max(50, e.width)))
        HoverText(self.editor_label, self.editor_var.get)
        actions = ttk.Frame(right, style='Card.TFrame')
        actions.pack(fill='x')
        self.listen_button = ttk.Button(actions, text='▶ 试听片段', command=self._start_preview)
        self.listen_button.pack(side='left')
        self.stop_button = ttk.Button(actions, text='■ 停止', command=self._stop_preview)
        self.stop_button.pack(side='left', padx=7)
        self.preview_label = ttk.Label(right, textvariable=self.preview_var, style='Muted.TLabel')
        self.preview_label.pack(anchor='w', pady=(5, 0))

        foot = ttk.Frame(outer, style='Card.TFrame', padding=(12, 10))
        foot.grid(row=4, column=0, sticky='ew', pady=(10, 0))
        directory = ttk.Frame(foot, style='Card.TFrame')
        directory.pack(fill='x')
        ttk.Label(directory, text='导出到', style='Card.TLabel').pack(side='left', padx=(0, 8))
        self.output_entry = ttk.Entry(directory, textvariable=self.output_var, state='readonly')
        self.output_entry.pack(side='left', fill='x', expand=True)
        self.output_button = ttk.Button(directory, text='选择目录', command=self._pick_output)
        self.output_button.pack(side='left', padx=6)
        self.overwrite_check = ttk.Checkbutton(directory, text='覆盖同名输出', variable=self.overwrite)
        self.overwrite_check.pack(side='left', padx=4)
        actions = ttk.Frame(foot, style='Card.TFrame')
        actions.pack(fill='x', pady=(8, 0))
        self.export_button = ttk.Button(actions, text='导出全部片段', command=self._export, style='Accent.TButton')
        self.export_button.pack(side='left')
        self.cancel_button = ttk.Button(actions, text='取消导出', command=self._cancel_export)
        self.cancel_button.pack(side='left', padx=6)
        self.retry_button = ttk.Button(actions, text='重试失败项', command=lambda: self._export(failed_only=True))
        self.retry_button.pack(side='left')
        self.progress = ttk.Progressbar(actions, mode='determinate', maximum=100)
        self.progress.pack(side='left', fill='x', expand=True, padx=12)
        ttk.Label(actions, textvariable=self.progress_label, style='Muted.TLabel').pack(side='left')
        self.result_button = ttk.Button(actions, text='查看结果', command=self._show_result)
        self.result_button.pack(side='right', padx=(10, 0))
        self.status_label = ttk.Label(foot, textvariable=self.status_var, style='Muted.TLabel', wraplength=1120, width=1)
        self.status_label.pack(anchor='w', fill='x', pady=(7, 0))
        self.status_label.bind('<Configure>', lambda e: self.status_label.configure(wraplength=max(50, e.width)))
        status = ttk.Frame(outer)
        status.grid(row=5, column=0, sticky='ew', pady=(7, 0))
        ttk.Label(status, textvariable=self.busy_var, style='Small.TLabel').pack(side='left', fill='x', expand=True)
        ttk.Label(status, textvariable=self.save_var, style='Small.TLabel').pack(side='right')
        ttk.Label(outer, textvariable=self.ffmpeg_var, style='Small.TLabel').grid(row=6, column=0, sticky='w', pady=(2, 0))
        self._draw_wave()

